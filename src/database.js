import { openPostgres, openSqlite } from './db-driver.js';
import { ADMIN_USERNAME, AppError } from './domain.js';

const metadataSchema = `
  CREATE TABLE IF NOT EXISTS metadata (
    name TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );
`;

const schema = (postgres) => {
  const primaryKey = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const view = postgres ? 'CREATE OR REPLACE VIEW inventory' : 'CREATE VIEW IF NOT EXISTS inventory';
  return `
  CREATE TABLE IF NOT EXISTS users (
    id ${primaryKey},
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('member', 'admin'))
  );
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
    csrf_token TEXT NOT NULL,
    expires_at BIGINT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS sessions_expiration ON sessions(expires_at);

  CREATE TABLE IF NOT EXISTS equipment (
    id ${primaryKey},
    name TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('mikrokontroler', 'motor', 'sensor', 'kit', 'perkakas')),
    description TEXT NOT NULL,
    image TEXT,
    total INTEGER NOT NULL CHECK (total BETWEEN 0 AND 999),
    active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
  );
  CREATE TABLE IF NOT EXISTS loans (
    id ${primaryKey},
    equipment_id INTEGER NOT NULL REFERENCES equipment(id),
    user_id INTEGER NOT NULL REFERENCES users(id),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 999),
    start_date TEXT NOT NULL,
    due_date TEXT NOT NULL,
    purpose TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'approved', 'borrowed', 'returned', 'declined', 'cancelled')),
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  );
  CREATE INDEX IF NOT EXISTS loans_equipment_status ON loans(equipment_id, status);
  CREATE INDEX IF NOT EXISTS loans_user ON loans(user_id);

  ${view} AS
    SELECT equipment.*,
      COALESCE(holds.reserved, 0) AS reserved,
      COALESCE(holds.borrowed, 0) AS borrowed,
      equipment.total - COALESCE(holds.reserved, 0) AS available
    FROM equipment
    LEFT JOIN (
      SELECT equipment_id, CAST(SUM(quantity) AS INTEGER) AS reserved,
        CAST(SUM(CASE WHEN status = 'borrowed' THEN quantity ELSE 0 END) AS INTEGER) AS borrowed
      FROM loans
      WHERE status IN ('approved', 'borrowed')
      GROUP BY equipment_id
    ) AS holds ON holds.equipment_id = equipment.id;
  `;
};

const adminLoginSchema = `
  ALTER TABLE users ADD COLUMN username TEXT CHECK (username IS NULL OR role = 'admin');
  ALTER TABLE users ADD COLUMN password_revision INTEGER NOT NULL DEFAULT 0;
  CREATE UNIQUE INDEX users_username ON users(username);
`;

const staffActions = new Map([
  ['approve', { from: 'pending', to: 'approved' }],
  ['decline', { from: 'pending', to: 'declined' }],
  ['pickup', { from: 'approved', to: 'borrowed' }],
  ['cancel', { from: 'approved', to: 'cancelled' }],
  ['return', { from: 'borrowed', to: 'returned' }],
]);

const loanDetails = `
  SELECT loans.*, equipment.name AS equipment_name, equipment.category,
    equipment.image, equipment.active AS equipment_active,
    users.name AS borrower, users.email AS borrower_email
  FROM loans
  JOIN equipment ON equipment.id = loans.equipment_id
  JOIN users ON users.id = loans.user_id
`;

const inventoryList = 'SELECT * FROM inventory ORDER BY active DESC, LOWER(name), id';

function records(connection) {
  const query = (sql, ...parameters) => connection.query(sql, parameters);
  async function first(sql, ...parameters) {
    return (await query(sql, ...parameters))[0];
  }

  return {
    query,
    userByEmail: (email) => first('SELECT * FROM users WHERE email = ?', email),
    adminByUsername: (username) => first("SELECT * FROM users WHERE username = ? AND role = 'admin'", username),
    async createUser(name, email, passwordHash, role, { username = null, passwordRevision = 0 } = {}) {
      const row = await first(`
        INSERT INTO users (name, email, password_hash, role, username, password_revision)
        VALUES (?, ?, ?, ?, ?, ?) RETURNING id
      `, name, email, passwordHash, role, username, passwordRevision);
      return row.id;
    },
    setAdminUsername: (id, username) => query("UPDATE users SET username = ? WHERE id = ? AND role = 'admin'", username, id),
    setAdminPassword: (id, hash, revision) => query(`
      UPDATE users SET password_hash = ?, password_revision = ? WHERE id = ? AND role = 'admin'
    `, hash, revision, id),
    async passwordIsCurrent(userId, hash) {
      return Boolean(await first('SELECT id FROM users WHERE id = ? AND password_hash = ?', userId, hash));
    },
    findSession: (hash, now) => first(`
      SELECT sessions.user_id, sessions.csrf_token, users.name, users.role
      FROM sessions LEFT JOIN users ON users.id = sessions.user_id
      WHERE token_hash = ? AND expires_at > ?
    `, hash, now),
    storeSession: (hash, userId, csrf, expires) => query('INSERT INTO sessions VALUES (?, ?, ?, ?)', hash, userId, csrf, expires),
    deleteSession: (hash) => query('DELETE FROM sessions WHERE token_hash = ?', hash),
    deleteUserSessions: (id) => query('DELETE FROM sessions WHERE user_id = ?', id),
    expireSessions: (now) => query('DELETE FROM sessions WHERE expires_at <= ?', now),
    catalog: () => query('SELECT * FROM inventory WHERE active = 1 ORDER BY id'),
    inventory: () => query(inventoryList),
    inventorySummary: () => query('SELECT name, category, image FROM equipment'),
    inventoryPage: (limit, offset) => query(inventoryList + ' LIMIT ? OFFSET ?', limit, offset),
    async equipment(id) {
      const item = await first('SELECT * FROM inventory WHERE id = ?', id);
      if (!item) throw new AppError(404, 'Alat ini tidak ditemukan.');
      return item;
    },
    async addEquipment(item) {
      const row = await first(`
        INSERT INTO equipment (name, category, description, total, active, image)
        VALUES (?, ?, ?, ?, ?, ?) RETURNING id
      `, item.name, item.category, item.description, item.total, item.active, item.image ?? null);
      return row.id;
    },
    async loan(id) {
      const loan = await first('SELECT * FROM loans WHERE id = ?', id);
      if (!loan) throw new AppError(404, 'Peminjaman ini tidak ditemukan.');
      return loan;
    },
    async addLoan(itemId, userId, form, status = 'pending') {
      const row = await first(`
        INSERT INTO loans (equipment_id, user_id, quantity, start_date, due_date, purpose, status)
        VALUES (?, ?, ?, ?, ?, ?, ?) RETURNING id
      `, itemId, userId, form.quantity, form.start, form.due, form.purpose, status);
      return row.id;
    },
    setLoanStatus: (id, status) => query('UPDATE loans SET status = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?', status, id),
    memberLoans: (userId) => query(loanDetails + ' WHERE loans.user_id = ? ORDER BY loans.updated_at DESC, loans.id DESC', userId),
    adminLoans: () => query(loanDetails + ' ORDER BY loans.updated_at DESC, loans.id DESC'),
    async hasMetadata(name) {
      return Boolean(await first('SELECT value FROM metadata WHERE name = ?', name));
    },
    setMetadata: (name, value) => query('INSERT INTO metadata (name, value) VALUES (?, ?)', name, value),
  };
}

export async function openInventory({ databasePath, databaseUrl }) {
  const driver = databaseUrl ? openPostgres(databaseUrl) : openSqlite(databasePath);
  try {
    await driver.transaction(async (connection) => {
      await connection.script(metadataSchema);
      const database = records(connection);
      if (!await database.hasMetadata('schema:v1')) {
        await connection.script(schema(driver.dialect === 'postgres'));
        await database.setMetadata('schema:v1', '1');
      }
      if (!await database.hasMetadata('schema:v2')) {
        await connection.script(adminLoginSchema);
        await database.query(`
          UPDATE users SET username = ?
          WHERE role = 'admin' AND (SELECT COUNT(*) FROM users WHERE role = 'admin') = 1
        `, ADMIN_USERNAME);
        await database.setMetadata('schema:v2', '1');
      }
    });
  } catch (error) {
    await driver.close();
    throw error;
  }

  const transaction = (work) => driver.transaction((connection) => work(records(connection)));
  return {
    ...records(driver),
    close: driver.close,
    ready: () => driver.query('SELECT 1'),
    transaction,
    updateEquipment(id, form) {
      return transaction(async (database) => {
        const item = await database.equipment(id);
        if (form.total < item.reserved) {
          throw new AppError(409, `Total stok minimal ${item.reserved} unit karena unit itu sedang dipinjam atau dipesan.`);
        }
        await database.query(
          'UPDATE equipment SET name = ?, category = ?, description = ?, total = ?, active = ? WHERE id = ?',
          form.name, form.category, form.description, form.total, form.active, id,
        );
      });
    },
    requestLoan(itemId, userId, form) {
      return transaction(async (database) => {
        const item = await database.equipment(itemId);
        if (!item.active) throw new AppError(404, 'Alat ini tidak tersedia di katalog.');
        if (form.quantity > item.available) {
          throw new AppError(409, 'Stok berubah. Periksa jumlah unit yang tersedia dan coba lagi.');
        }
        return database.addLoan(itemId, userId, form);
      });
    },
    cancelLoan(id, userId) {
      return transaction(async (database) => {
        const loan = await database.loan(id);
        if (loan.user_id !== userId) throw new AppError(404, 'Peminjaman ini tidak ditemukan.');
        if (loan.status !== 'pending' && loan.status !== 'approved') {
          throw new AppError(409, 'Pengajuan ini tidak bisa dibatalkan.');
        }
        await database.setLoanStatus(id, 'cancelled');
      });
    },
    async advanceLoan(id, action, today) {
      const transition = staffActions.get(action);
      if (!transition) throw new AppError(400, 'Tindakan peminjaman tidak dikenal.');

      await transaction(async (database) => {
        const loan = await database.loan(id);
        if (loan.status !== transition.from) {
          throw new AppError(409, 'Status pengajuan sudah berubah. Muat ulang daftar peminjaman.');
        }
        if (action === 'approve') {
          const item = await database.equipment(loan.equipment_id);
          if (loan.due_date < today) throw new AppError(409, 'Tanggal kembali pengajuan ini sudah lewat.');
          if (!item.active || item.available < loan.quantity) {
            throw new AppError(409, 'Stok yang dapat dipinjam belum cukup untuk menyetujui pengajuan ini.');
          }
        }
        if (action === 'pickup' && (today < loan.start_date || today > loan.due_date)) {
          throw new AppError(409, 'Catat pengambilan dalam rentang tanggal pinjaman.');
        }
        await database.setLoanStatus(id, transition.to);
      });
      return transition.to;
    },
  };
}
