import { AppError, bundleAvailability } from './domain.js';

export function labSchema(postgres) {
  const key = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  return `
    CREATE TABLE loan_groups (
      id ${key},
      title TEXT NOT NULL
    );
    ALTER TABLE loans ADD COLUMN group_id INTEGER REFERENCES loan_groups(id);
    CREATE INDEX loans_group ON loans(group_id);

    CREATE TABLE return_checks (
      loan_id INTEGER PRIMARY KEY REFERENCES loans(id),
      service_quantity INTEGER NOT NULL CHECK (service_quantity BETWEEN 0 AND 999),
      note TEXT NOT NULL,
      checked_on TEXT NOT NULL,
      resolved_on TEXT
    );
    CREATE INDEX return_checks_open ON return_checks(resolved_on) WHERE service_quantity > 0;

    CREATE TABLE project_kits (
      id ${key},
      title TEXT NOT NULL,
      description TEXT NOT NULL,
      active INTEGER NOT NULL CHECK (active IN (0, 1))
    );
    CREATE TABLE kit_parts (
      kit_id INTEGER NOT NULL REFERENCES project_kits(id) ON DELETE CASCADE,
      equipment_id INTEGER NOT NULL REFERENCES equipment(id),
      quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 999),
      position INTEGER NOT NULL,
      PRIMARY KEY (kit_id, equipment_id)
    );

    CREATE TABLE gallery_projects (
      id ${key},
      loan_id INTEGER NOT NULL UNIQUE REFERENCES loans(id),
      title TEXT NOT NULL,
      description TEXT NOT NULL,
      photo_type TEXT,
      photo ${postgres ? 'BYTEA' : 'BLOB'},
      published_on TEXT NOT NULL
    );

    CREATE TABLE club_events (
      id ${key},
      name TEXT NOT NULL,
      event_date TEXT NOT NULL
    );
    CREATE TABLE event_needs (
      id ${key},
      event_id INTEGER NOT NULL REFERENCES club_events(id) ON DELETE CASCADE,
      team TEXT NOT NULL,
      equipment_id INTEGER NOT NULL REFERENCES equipment(id),
      quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 999),
      UNIQUE (event_id, team, equipment_id)
    );

    ${postgres ? 'CREATE OR REPLACE VIEW inventory AS' : 'DROP VIEW inventory; CREATE VIEW inventory AS'}
    SELECT equipment.*,
      COALESCE(holds.reserved, 0) AS reserved,
      COALESCE(holds.borrowed, 0) AS borrowed,
      equipment.total - COALESCE(holds.reserved, 0) - COALESCE(service.units, 0) AS available,
      COALESCE(service.units, 0) AS service
    FROM equipment
    LEFT JOIN (
      SELECT equipment_id, CAST(SUM(quantity) AS INTEGER) AS reserved,
        CAST(SUM(CASE WHEN status = 'borrowed' THEN quantity ELSE 0 END) AS INTEGER) AS borrowed
      FROM loans
      WHERE status IN ('approved', 'borrowed')
      GROUP BY equipment_id
    ) AS holds ON holds.equipment_id = equipment.id
    LEFT JOIN (
      SELECT loans.equipment_id, CAST(SUM(return_checks.service_quantity) AS INTEGER) AS units
      FROM return_checks JOIN loans ON loans.id = return_checks.loan_id
      WHERE return_checks.service_quantity > 0 AND return_checks.resolved_on IS NULL
      GROUP BY loans.equipment_id
    ) AS service ON service.equipment_id = equipment.id;
  `;
}

const selectedPart = 'i.id AS equipment_id, i.name AS equipment_name, i.active AS equipment_active, i.available, i.image, i.category';
const kitDetails = `
  SELECT k.id, k.title, k.description, k.active, p.quantity, ${selectedPart}
  FROM project_kits k JOIN kit_parts p ON p.kit_id = k.id
  JOIN inventory i ON i.id = p.equipment_id
`;
const galleryDetails = `
  SELECT gallery_projects.id, gallery_projects.loan_id, gallery_projects.title, gallery_projects.description, photo_type, published_on,
    users.name AS author, users.id AS author_id, equipment.image, equipment.category
  FROM gallery_projects
  JOIN loans ON loans.id = gallery_projects.loan_id
  JOIN users ON users.id = loans.user_id
  JOIN equipment ON equipment.id = loans.equipment_id
`;
const serviceDetails = `
  SELECT return_checks.*, loans.equipment_id, equipment.name AS equipment_name
  FROM return_checks
  JOIN loans ON loans.id = return_checks.loan_id
  JOIN equipment ON equipment.id = loans.equipment_id
  WHERE service_quantity > 0
`;

function kitsFromRows(rows) {
  const kits = new Map();
  for (const part of rows) {
    if (!kits.has(part.id)) {
      const { id, title, description, active, image, category } = part;
      kits.set(id, { id, title, description, active, image, category, parts: [] });
    }
    kits.get(part.id).parts.push(part);
  }
  return [...kits.values()].map((kit) => ({ ...kit, available: bundleAvailability(kit.parts) }));
}

export function labRecords({ query, first }) {
  return {
    async listKits(publicOnly = true) {
      const filter = publicOnly ? ' WHERE k.active = 1' : '';
      return kitsFromRows(await query(kitDetails + filter + ' ORDER BY k.id, p.position'));
    },
    async kit(id) {
      const [kit] = kitsFromRows(await query(kitDetails + ' WHERE k.id = ? ORDER BY p.position', id));
      if (!kit) throw new AppError(404, 'Kit proyek ini tidak ditemukan.');
      return kit;
    },
    async saveKit(id, { title, description, active, parts }) {
      if (id) {
        const updated = await first('UPDATE project_kits SET title = ?, description = ?, active = ? WHERE id = ? RETURNING id',
          title, description, active, id);
        if (!updated) throw new AppError(404, 'Kit proyek ini tidak ditemukan.');
        await query('DELETE FROM kit_parts WHERE kit_id = ?', id);
      } else {
        const created = await first('INSERT INTO project_kits (title, description, active) VALUES (?, ?, ?) RETURNING id',
          title, description, active);
        id = created.id;
      }
      for (const [position, { equipmentId, quantity }] of parts.entries()) {
        await query('INSERT INTO kit_parts (kit_id, equipment_id, quantity, position) VALUES (?, ?, ?, ?)',
          id, equipmentId, quantity, position);
      }
      return id;
    },
    async addLoanGroup(title) {
      return (await first('INSERT INTO loan_groups (title) VALUES (?) RETURNING id', title)).id;
    },
    recordReturn: (loanId, quantity, note, today) => query(
      'INSERT INTO return_checks (loan_id, service_quantity, note, checked_on) VALUES (?, ?, ?, ?)',
      loanId, quantity, note, today,
    ),
    serviceList: (resolved = false) => query(
      serviceDetails + (resolved ? ' AND resolved_on IS NOT NULL ORDER BY resolved_on DESC, loan_id DESC'
        : ' AND resolved_on IS NULL ORDER BY checked_on, loan_id'),
    ),
    async completeService(loanId, today) {
      const row = await first(`
        UPDATE return_checks SET resolved_on = ?
        WHERE loan_id = ? AND service_quantity > 0 AND resolved_on IS NULL RETURNING loan_id
      `, today, loanId);
      if (!row) throw new AppError(409, 'Servis ini sudah selesai atau tidak ditemukan.');
    },
    listProjects: (limit = 30) => query(galleryDetails + ' ORDER BY gallery_projects.id DESC LIMIT ?', limit),
    async project(id) {
      const project = await first(galleryDetails + ' WHERE gallery_projects.id = ?', id);
      if (!project) throw new AppError(404, 'Rakitan ini tidak ditemukan.');
      const parts = await query(`
        SELECT component.quantity, ${selectedPart}
        FROM loans anchor JOIN loans component
          ON component.id = anchor.id OR component.group_id = anchor.group_id
        JOIN inventory i ON i.id = component.equipment_id
        WHERE anchor.id = ? ORDER BY component.id
      `, project.loan_id);
      return { ...project, parts, active: 1, available: bundleAvailability(parts) };
    },
    projectPhoto: (id) => first('SELECT photo, photo_type FROM gallery_projects WHERE id = ? AND photo IS NOT NULL', id),
    async addProject(loanId, { title, description, photo, photoType }, today) {
      const added = await first(`
        INSERT INTO gallery_projects (loan_id, title, description, photo, photo_type, published_on)
        VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT (loan_id) DO NOTHING RETURNING id
      `, loanId, title, description, photo ?? null, photoType ?? null, today);
      return added?.id ?? (await first('SELECT id FROM gallery_projects WHERE loan_id = ?', loanId)).id;
    },
    removeProject: (id) => query('DELETE FROM gallery_projects WHERE id = ?', id),
    events: () => query('SELECT * FROM club_events ORDER BY event_date DESC, id DESC'),
    async event(id) {
      const event = await first('SELECT * FROM club_events WHERE id = ?', id);
      if (!event) throw new AppError(404, 'Kegiatan ini tidak ditemukan.');
      const needs = await query(`
        SELECT event_needs.id, team, quantity, ${selectedPart}
        FROM event_needs JOIN inventory i ON i.id = event_needs.equipment_id
        WHERE event_id = ? ORDER BY LOWER(team), LOWER(i.name)
      `, id);
      return { ...event, needs };
    },
    async saveEvent(id, name, date) {
      if (id) {
        const changed = await first('UPDATE club_events SET name = ?, event_date = ? WHERE id = ? RETURNING id',
          name, date, id);
        if (!changed) throw new AppError(404, 'Kegiatan ini tidak ditemukan.');
        return changed.id;
      }
      return (await first('INSERT INTO club_events (name, event_date) VALUES (?, ?) RETURNING id', name, date)).id;
    },
    addEventNeed: (eventId, team, itemId, quantity) => query(`
      INSERT INTO event_needs (event_id, team, equipment_id, quantity) VALUES (?, ?, ?, ?)
      ON CONFLICT (event_id, team, equipment_id) DO UPDATE SET quantity = excluded.quantity
    `, eventId, team, itemId, quantity),
    removeEventNeed: (eventId, id) => query('DELETE FROM event_needs WHERE event_id = ? AND id = ?', eventId, id),
  };
}
