export const equipmentSamples = [...starterEquipment, ...expandedEquipment];

const equipmentKey = (item) => item.category + ':' + item.name.trim().replace(/\s+/g, ' ').toLowerCase();

export function missingEquipment(existing, samples = equipmentSamples) {
  const images = new Set(existing.map((item) => item.image).filter(Boolean));
  const names = new Set(existing.map(equipmentKey));
  return samples.filter((item) => !images.has(item.image) && !names.has(equipmentKey(item)));
}

export async function addMissingEquipment(database, existing, { samples = equipmentSamples, sampleStock = false } = {}) {
  const items = missingEquipment(existing, samples);
  for (const item of items) {
    await database.addEquipment({
      ...item,
      total: sampleStock ? item.total : 0,
      active: sampleStock ? 1 : 0,
    });
  }
  return items.length;
}
